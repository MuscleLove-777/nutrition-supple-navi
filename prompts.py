"""栄養＆サプリナビ - プロンプト定義

プロテイン・サプリメント・食事管理ブログ用のプロンプトを一元管理する。
"""


def build_keyword_prompt(config):
    """キーワード選定プロンプトを構築する"""
    categories_text = "\n".join(f"- {cat}" for cat in config.TARGET_CATEGORIES)
    return (
        "筋トレ向けの栄養・サプリメント情報ブログ用のキーワードを選定してください。\n\n"
        "以下のカテゴリから1つ選び、そのカテゴリで今注目されている"
        "プロテイン・サプリ・栄養管理関連のキーワードを1つ提案してください。\n\n"
        f"カテゴリ一覧:\n{categories_text}\n\n"
        "筋トレ初心者〜中級者がプロテインやサプリを選ぶときに検索しそうなキーワードを意識してください。\n"
        "コスパ、成分比較、タイミングなど実用的なトピックを優先してください。\n\n"
        "以下の形式でJSON形式のみで回答してください（説明不要）:\n"
        '{"category": "カテゴリ名", "keyword": "キーワード"}'
    )


def build_article_prompt(keyword, category, config):
    """栄養・サプリ用の記事生成プロンプトを構築する"""
    return f"""あなたはスポーツ栄養学の専門家であり、サプリメントアドバイザーです。

以下のキーワードに関する栄養・サプリメント情報を、初心者にもわかりやすい記事にしてください。

【基本条件】
- ブログ名: {config.BLOG_NAME}
- キーワード: {keyword}
- カテゴリ: {category}
- 言語: 日本語
- 文字数: {config.MAX_ARTICLE_LENGTH}文字以内

【記事フォーマット】
## 3行でわかるポイント
- ポイント1
- ポイント2
- ポイント3

## 栄養学的な解説
（成分・効果・メカニズムを科学的に解説）

## おすすめの選び方
（コスパ・成分量・品質で比較するポイント）

## 摂取タイミングと量
（いつ・どれくらい摂るのが最適か）

## 注意点・副作用
（過剰摂取のリスクや相互作用）

## まとめ
（コスパ最強の選び方まとめ）

【SEO要件】
1. タイトルにキーワード「{keyword}」を必ず含めること
2. タイトルは32文字以内で魅力的に
3. H2、H3の見出し構造を適切に使用すること
4. キーワード密度は{config.MIN_KEYWORD_DENSITY}%〜{config.MAX_KEYWORD_DENSITY}%を目安に
5. メタディスクリプションは{config.META_DESCRIPTION_LENGTH}文字以内

【条件】
- {config.MAX_ARTICLE_LENGTH}文字以内
- 具体的な成分量・価格・コスパを含める
- 科学的根拠を示す（研究データや栄養学的事実）
- 内部リンクのプレースホルダーを2〜3箇所に配置（{{{{internal_link:関連トピック}}}}の形式）

【出力形式】
以下のJSON形式で出力してください。JSONブロック以外のテキストは出力しないでください。

```json
{{
  "title": "SEO最適化されたタイトル",
  "content": "# タイトル\\n\\n本文（Markdown形式）...",
  "meta_description": "120文字以内のメタディスクリプション",
  "tags": ["タグ1", "タグ2", "タグ3", "タグ4", "タグ5"],
  "slug": "url-friendly-slug"
}}
```

【注意事項】
- content内のMarkdownは適切にエスケープしてJSON文字列として有効にすること
- tagsは5個ちょうど生成すること
- slugは半角英数字とハイフンのみ使用すること
- 医療的なアドバイスは避け、あくまでサプリメント・栄養の情報提供に留めること
- アレルギーや持病がある場合は医師に相談するよう注意喚起を入れること"""
